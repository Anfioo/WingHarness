//! Windows-safe name validation (reserved names, trailing dots/spaces, control
//! characters, length limits) for on-disk workspace artifacts.

use crate::error::{AppError, AppResult};

/// Characters Windows forbids in a path component.
const ILLEGAL: &[char] = &['<', '>', ':', '"', '/', '\\', '|', '?', '*'];

/// Reserved DOS device names. Windows treats these as devices even with an
/// extension (`CON.txt`), so the comparison uses the stem before the first dot.
const RESERVED: &[&str] = &[
    "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8",
    "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9",
];

/// The longest name we accept, in characters. Well under Windows' 255-char
/// component limit, leaving room for the `.json` suffix and temp files.
const MAX_NAME_CHARS: usize = 100;

/// The longest workspace id we accept. Ids are frontend UUIDs, so this is only
/// a sanity bound.
const MAX_ID_CHARS: usize = 64;

/// Clean a user-supplied name and validate it for use as a file component.
///
/// Leading/trailing whitespace and trailing dots are trimmed (Windows drops
/// them silently, which would make two names collide). Everything else that
/// cannot be stored verbatim is rejected rather than guessed at, so the caller
/// can surface a clear error.
pub fn sanitize_name(name: &str) -> AppResult<String> {
    let cleaned = name.trim().trim_end_matches(['.', ' ']).trim_end();
    if cleaned.is_empty() {
        return Err(AppError::other("name must not be empty"));
    }
    if cleaned.chars().count() > MAX_NAME_CHARS {
        return Err(AppError::other(format!(
            "name must be at most {MAX_NAME_CHARS} characters"
        )));
    }
    if let Some(bad) = cleaned.chars().find(|c| c.is_control() || ILLEGAL.contains(c)) {
        return Err(AppError::other(format!("name contains an illegal character: {bad:?}")));
    }
    let stem = cleaned.split('.').next().unwrap_or(cleaned).to_ascii_uppercase();
    if RESERVED.contains(&stem.as_str()) {
        return Err(AppError::other(format!(
            "name {cleaned:?} is a reserved device name on Windows"
        )));
    }
    Ok(cleaned.to_string())
}

/// Derive the storage file name (`<id>.json`) for a workspace id. Ids are
/// generated by the frontend, but this is a system boundary, so reject anything
/// that could escape the data directory.
pub fn workspace_file(id: &str) -> AppResult<String> {
    if id.is_empty() {
        return Err(AppError::other("workspace id must not be empty"));
    }
    if id.chars().count() > MAX_ID_CHARS {
        return Err(AppError::other("workspace id is too long"));
    }
    if !id
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        return Err(AppError::other(format!("invalid workspace id: {id:?}")));
    }
    Ok(format!("{id}.json"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_ordinary_names() {
        assert_eq!(sanitize_name("My API").unwrap(), "My API");
        assert_eq!(sanitize_name("  spaced  ").unwrap(), "spaced");
        assert_eq!(sanitize_name("trailing...").unwrap(), "trailing");
    }

    #[test]
    fn rejects_dangerous_names() {
        assert!(sanitize_name("").is_err());
        assert!(sanitize_name("   ").is_err());
        assert!(sanitize_name("a/b").is_err());
        assert!(sanitize_name("a\\b").is_err());
        assert!(sanitize_name("a?b").is_err());
        assert!(sanitize_name("con").is_err());
        assert!(sanitize_name("NUL.txt").is_err());
        assert!(sanitize_name("com5").is_err());
        assert!(sanitize_name("with\ttab").is_err());
        assert!(sanitize_name(&"x".repeat(101)).is_err());
    }

    #[test]
    fn workspace_files_are_flat() {
        assert_eq!(workspace_file("abc-123").unwrap(), "abc-123.json");
        assert!(workspace_file("").is_err());
        assert!(workspace_file("../escape").is_err());
        assert!(workspace_file("a/b").is_err());
        assert!(workspace_file("a\\b").is_err());
    }
}