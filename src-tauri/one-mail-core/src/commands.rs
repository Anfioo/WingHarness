//! The Tauri command surface: 32 thin forwards.
//!
//! Every command resolves the pool (or forwards the state) and calls the
//! domain function. The few events a domain function cannot emit on its own —
//! accounts and outbox changes, because those functions only receive the pool —
//! are emitted here.
//!
//! These names are mirrored in `src-tauri/src/invoke.rs`, `build.rs`,
//! `capabilities/default.json` and `permissions/autogenerated/one_mail_*.toml`.
//! Renaming one without the other three breaks the ACL at runtime.

