#[tauri::command]
pub async fn one_mail_settings_set(
    state: State<'_, OneMailState>,
    settings: OneMailSettings,
) -> OneMailResult<OneMailSettings> {
    crate::settings::validate(&settings)?;
    let saved = crate::settings::write(&settings)?;
    state.emit(EVENT_SETTINGS_CHANGED, saved.clone());
    Ok(saved)
}
