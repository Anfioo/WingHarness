#[tauri::command]
pub async fn one_mail_compose_reply_draft(
    state: State<'_, OneMailState>,
    message_id: i64,
    mode: String,
) -> OneMailResult<Draft> {
    let pool = state.pool().await?;
    let reply_all = match mode.as_str() {
        "reply" => false,
        "reply_all" => true,
        _ => {
            return Err(OneMailError::invalid_input(
                "mode",
                "The reply mode must be \"reply\" or \"reply_all\".",
            ))
        }
    };
    let draft = compose::reply_draft(&pool, message_id, reply_all).await?;
    state.emit(
        EVENT_OUTBOX_CHANGED,
        OutboxChangedPayload {
            outbox_id: Some(draft.outbox_id),
        },
    );
    Ok(draft)
}

