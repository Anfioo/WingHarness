const BY_NAME = new Map(ICON_CATALOG.map((option) => [option.name, option.icon]));

/**
 * Custom icons are referenced by `custom:<file stem>`, keeping them apart from
 * the catalog names a build carries. The prefix is what tells the two apart, so
 * a custom file may be named after a lucide icon without shadowing it.
 */
export const CUSTOM_ICON_PREFIX = "custom:";

/** The file stem a stored value names, or `null` for a catalog name. */
export function customIconName(value: string | null | undefined): string | null {
  if (!value?.startsWith(CUSTOM_ICON_PREFIX)) return null;
  return value.slice(CUSTOM_ICON_PREFIX.length) || null;
}

/**
 * The icon a layout entry asks for, or `null` when it names none — or one this
 * build does not carry, which the sidebar then draws with its own default.
 */
export function resolveSidebarIcon(name: string | null | undefined): AppRouteIcon | null {
  if (!name) return null;
  return BY_NAME.get(name) ?? null;
}

/**
 * The custom SVG a layout entry asks for, or `null` when it names a catalog
 * icon, or a file the folder no longer holds.
 */
export function resolveCustomIcon(
  name: string | null | undefined,
  custom: Map<string, AppRouteIcon> | undefined
): AppRouteIcon | null {
  const key = customIconName(name);
  if (!key) return null;
  return custom?.get(key) ?? null;
}

/** The component a stored icon value draws, across both catalogs. */
export function resolveIcon(
  name: string | null | undefined,
  custom: Map<string, AppRouteIcon> | undefined
): AppRouteIcon | null {
  return resolveSidebarIcon(name) ?? resolveCustomIcon(name, custom);
}
