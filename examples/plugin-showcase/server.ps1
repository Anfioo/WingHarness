# Serves one small page on a local port, PowerShell 5.1 only (no dependencies).
#
# The app sets only two variables: PLUGIN_ID and PLUGIN_DIR. Every setting lives
# in a file this script reads itself, from PLUGIN_DIR -- the same files the
# config window edits. This page renders them back, so a change in the config
# window shows up on reload.
#
# It runs in the foreground on purpose: the app streams a script's output until
# it exits, so a detached server would be unkillable from the settings page.
# Stopping from the page, or Ctrl+C, ends the run normally.
#
# This file is deliberately ASCII-only. PowerShell 5.1 reads a .ps1 as ANSI
# (GBK on a Chinese Windows) unless it carries a UTF-8 BOM, so non-ASCII here
# would corrupt on parse. User-facing text is English or comes from the config
# files, which are read as UTF-8 data.

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Web

$root = if ($env:PLUGIN_DIR) { $env:PLUGIN_DIR } else { $PSScriptRoot }
$generatedExisted = $false

function Write-Log($message) {
    Write-Output "[plugin-showcase] $message"
}

function Html($text) {
    return [System.Web.HttpUtility]::HtmlEncode([string]$text)
}

# --- config readers, one per format the manifest declares -------------------

function Read-DotEnv($path) {
    $values = [ordered]@{}
    if (-not (Test-Path $path)) { return $values }
    foreach ($line in Get-Content -LiteralPath $path -Encoding UTF8) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith('#') -or -not $trimmed.Contains('=')) { continue }
        $key, $value = $trimmed -split '=', 2
        $values[$key.Trim()] = $value.Trim().Trim('"').Trim("'")
    }
    return $values
}

function Read-Json($path) {
    if (-not (Test-Path $path)) { return $null }
    return (Get-Content -LiteralPath $path -Raw -Encoding UTF8 | ConvertFrom-Json)
}

function Read-Yaml($path) {
    # A tiny reader: one level of nesting, enough for this demo's scalars.
    $values = [ordered]@{}
    if (-not (Test-Path $path)) { return $values }
    $current = $null
    foreach ($raw in Get-Content -LiteralPath $path -Encoding UTF8) {
        if (-not $raw.Trim() -or $raw.Trim().StartsWith('#')) { continue }
        $key, $value = $raw -split ':', 2
        if ($raw -notmatch '^\s') {
            $current = $key.Trim()
            $values[$current] = [ordered]@{}
            if ($value -and $value.Trim()) { $values[$current] = Convert-Scalar $value.Trim() }
            continue
        }
        if ($null -eq $current) { continue }
        $values[$current][$key.Trim()] = Convert-Scalar $value.Trim()
    }
    return $values
}

function Convert-Scalar($text) {
    $text = $text.Trim().Trim('"').Trim("'")
    if ($text -eq 'true') { return $true }
    if ($text -eq 'false') { return $false }
    $number = 0
    if ([int]::TryParse($text, [ref]$number)) { return $number }
    return $text
}

function New-GeneratedFile($path) {
    # Creates generated.yml on first boot -- the startmust:false case.
    if (Test-Path $path) { return $false }
    $stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')
    $text = "# Generated by server.ps1 on first boot.`r`ngenerated:`r`n  at: '$stamp'`r`n"
    Set-Content -LiteralPath $path -Value $text -Encoding UTF8
    return $true
}

# --- a dot path through the parsed object graph ------------------------------

function Get-Path($root, $path) {
    $current = $root
    foreach ($segment in $path.Split('.')) {
        if ($null -eq $current) { return $null }
        $current = $current.$segment
    }
    return $current
}

function Format-Value($value) {
    if ($value -is [bool]) { if ($value) { return 'on' } else { return 'off' } }
    if ($null -eq $value) { return '' }
    return [string]$value
}

function New-Rows($pairs) {
    $html = ''
    foreach ($pair in $pairs) {
        $html += "<tr><td class=`"k`">$(Html $pair.Key)</td><td>$(Html (Format-Value $pair.Value))</td></tr>`n"
    }
    return $html
}

# Flattens one level of a nested reader result into dotted key/value rows.
function New-Flat($mapping) {
    $rows = @()
    if ($null -eq $mapping) { return $rows }
    foreach ($key in $mapping.Keys) {
        $value = $mapping[$key]
        if ($value -is [System.Collections.IDictionary]) {
            foreach ($inner in $value.Keys) {
                $rows += [pscustomobject]@{ Key = "$key.$inner"; Value = $value[$inner] }
            }
        } else {
            $rows += [pscustomobject]@{ Key = $key; Value = $value }
        }
    }
    return $rows
}

function New-Page {
    $envValues = Read-DotEnv (Join-Path $root '.env')
    $document = Read-Json (Join-Path $root 'cfg.json')
    $yamlDoc = Read-Yaml (Join-Path $root 'cfg.yaml')
    $generated = Read-Yaml (Join-Path $root 'generated.yml')

    $title = if ($envValues['SHOWCASE_TITLE']) { $envValues['SHOWCASE_TITLE'] } else { 'Plugin Showcase' }
    $theme = if ($envValues['SHOWCASE_THEME']) { $envValues['SHOWCASE_THEME'] } else { 'auto' }
    $colorScheme = switch ($theme) { 'light' { 'light' } 'dark' { 'dark' } default { 'light dark' } }
    $accent = switch ([string](Get-Path $document 'app.accent')) {
        'green' { '#059669' } 'orange' { '#ea580c' } default { '#2563eb' }
    }

    $tagline = [string](Get-Path $yamlDoc 'site.tagline')
    $note = [string](Get-Path $document 'app.note')
    $noteBlock = if ($note) { "<blockquote>$(Html $note)</blockquote>`n" } else { '' }

    $envRows = New-Flat (Read-DotEnv (Join-Path $root '.env'))

    $jsonRows = @()
    if ($null -ne $document) {
        foreach ($entry in $document.psobject.Properties) {
            if ($entry.Value -is [System.Management.Automation.PSCustomObject]) {
                foreach ($inner in $entry.Value.psobject.Properties) {
                    $jsonRows += [pscustomobject]@{ Key = "$($entry.Name).$($inner.Name)"; Value = $inner.Value }
                }
            } else {
                $jsonRows += [pscustomobject]@{ Key = $entry.Name; Value = $entry.Value }
            }
        }
    }

    $generatedBadge = if ($script:generatedExisted) { '' } else { '<code>new</code>' }

    $hostText = Html $envValues['SHOWCASE_HOST']
    $portText = Html $envValues['SHOWCASE_PORT']

    return @"
<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>$(Html $title)</title>
<style>
  :root { color-scheme: $colorScheme; }
  body { font: 15px/1.6 system-ui, sans-serif; margin: 0 auto; max-width: 46rem; padding: 3rem 1.5rem; }
  h1 { color: $accent; margin: 0 0 .25rem; }
  h2 { font-size: .95rem; margin: 2rem 0 .5rem; font-family: ui-monospace, monospace; }
  p.sub { opacity: .65; margin: 0; }
  table { border-collapse: collapse; width: 100%; }
  td { padding: .35rem 1rem .35rem 0; border-top: 1px solid rgba(127,127,127,.25); vertical-align: top; }
  td.k { opacity: .65; white-space: nowrap; }
  code { background: rgba(127,127,127,.15); padding: .1rem .35rem; border-radius: 4px; }
  blockquote { margin: 1.5rem 0 0; padding: .75rem 1rem; background: rgba(127,127,127,.1); border-radius: 8px; white-space: pre-wrap; }
  form { margin-top: 2rem; }
  button { font: inherit; padding: .45rem 1rem; border-radius: 8px; cursor: pointer; border: 1px solid rgba(127,127,127,.4); background: transparent; color: inherit; }
  button:hover { border-color: $accent; color: $accent; }
</style>
</head>
<body>
<h1>$(Html $title)</h1>
<p class="sub">$(Html $tagline) - <code>$hostText`:$portText</code></p>

<h2>.env</h2>
<table>$(New-Rows $envRows)</table>

<h2>cfg.json</h2>
<table>$(New-Rows $jsonRows)</table>

<h2>cfg.yaml</h2>
<table>$(New-Rows (New-Flat $yamlDoc))</table>

<h2>generated.yml $generatedBadge</h2>
<table>$(New-Rows (New-Flat $generated))</table>
$noteBlock

<form method="post" action="/shutdown">
  <button type="submit">Stop server</button>
</form>
</body>
</html>
"@
}

# --- the server --------------------------------------------------------------

$created = New-GeneratedFile (Join-Path $root 'generated.yml')
$script:generatedExisted = -not $created
if ($created) { Write-Log 'created generated.yml on first boot' } else { Write-Log 'generated.yml already present' }

$envValues = Read-DotEnv (Join-Path $root '.env')
$hostAddr = if ($envValues['SHOWCASE_HOST']) { $envValues['SHOWCASE_HOST'] } else { '127.0.0.1' }
$port = 8123
if ($envValues['SHOWCASE_PORT']) { [void][int]::TryParse($envValues['SHOWCASE_PORT'], [ref]$port) }

$listener = New-Object System.Net.HttpListener
$listener.Prefixes.Add("http://$hostAddr`:$port/")
try { $listener.Start() } catch {
    Write-Log "cannot listen on $hostAddr`:$port -- $($_.Exception.Message)"
    exit 1
}

Write-Log "plugin id : $($env:PLUGIN_ID)"
Write-Log "plugin dir: $root"
Write-Log "serving   : http://$hostAddr`:$port/"
Write-Log 'stop with : the button on the page, or Ctrl+C'

$shuttingDown = $false
try {
    while ($listener.IsListening) {
        $context = $listener.GetContext()
        $request = $context.Request
        $response = $context.Response
        $body = ''
        $status = 200
        $contentType = 'text/html; charset=utf-8'
        $path = $request.Url.AbsolutePath

        if ($request.HttpMethod -eq 'POST' -and $path -eq '/shutdown') {
            $body = 'Stopped. You can close this tab.'
            $contentType = 'text/plain; charset=utf-8'
            # Reply first, then stop. Stopping the listener closes the response
            # stream, so the write above has to land before this.
            $shuttingDown = $true
        } elseif ($request.HttpMethod -eq 'GET' -and ($path -eq '/' -or $path -eq '/index.html')) {
            $body = New-Page
        } else {
            $status = 404
            $body = 'Not found'
            $contentType = 'text/plain; charset=utf-8'
        }

        $payload = [System.Text.Encoding]::UTF8.GetBytes($body)
        $response.StatusCode = $status
        $response.ContentType = $contentType
        $response.ContentLength64 = $payload.Length
        $response.OutputStream.Write($payload, 0, $payload.Length)
        $response.OutputStream.Close()

        if ($shuttingDown) { $listener.Stop() }
    }
} finally {
    $listener.Close()
}

Write-Log 'stopped.'
exit 0
